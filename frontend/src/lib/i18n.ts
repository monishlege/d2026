function normalizeLanguage(language?: string): SiteLanguage {
  if (language === "hi" || language === "kn") {
    return language;
  }
  return "en";
}

export function getSiteText(key: string, language?: string): string {
  const normalizedLanguage = normalizeLanguage(language);
  return translations[normalizedLanguage][key] ?? translations.en[key] ?? key;
}

export function detectLanguageFromText(text: string): SiteLanguage {
  const normalized = text?.trim();
  if (!normalized) {
    return "en";
  }

  const hasKannada = /[\u0C80-\u0CFF]/.test(normalized);
  const hasDevanagari = /[\u0900-\u097F]/.test(normalized);
  if (hasKannada) {
    return "kn";
  }
  if (hasDevanagari) {
    return "hi";
  }

  const romanHindi = /\b(kya|hai|nahi|kripya|dhanyavaad|shukriya|namaste|aap|mujhe)\b/i;
  if (romanHindi.test(normalized)) {
    return "hi";
  }

  return "en";
}

export function getSiteLanguageLabel(language: SiteLanguage): string {
  return {
    en: "English",
    hi: "हिंदी",
    kn: "ಕನ್ನಡ",
  }[language];
}

